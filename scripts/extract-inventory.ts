/**
 * Generates docs/requirements/form-field-inventory.md from the canonical form definitions.
 * Run: npm run forms:inventory   (CI checks the committed file is up to date)
 */
import { writeFileSync } from "node:fs";
import { listFormDefinitions } from "~/modules/forms/registry";
import type { FieldDef, FormDefinition, ScalarField } from "~/modules/forms/types";

const TEST_REF =
  "tests/unit/docx-render.test.ts (binding + value presence); tests/integration/workflow.test.ts (submission + PDF)";

function type(f: FieldDef | ScalarField): string {
  switch (f.kind) {
    case "select":
      return `select (${f.options.map((o) => o.value).join(" / ")})`;
    case "text":
      return `text${f.maxLength ? ` ≤${f.maxLength}` : ""}${f.uppercase ? ", upper-case" : ""}`;
    case "textarea":
      return `long text${f.maxLength ? ` ≤${f.maxLength}` : ""}`;
    case "number":
      return `number${f.integer ? " (integer)" : ""}${f.max !== undefined ? ` ${f.min ?? 0}–${f.max}` : ""}`;
    case "date":
      return "date (DD-MM-YYYY on form)";
    case "monthYear":
      return "month & year";
    case "derived":
      return `derived from ${f.derivedFrom}`;
    case "table":
      return `table, ${f.templateRows} printed rows, max ${f.maxRows}`;
    case "list":
      return `list, ~${f.templateCapacity} printed lines, max ${f.maxItems}`;
  }
}

function validation(f: FieldDef | ScalarField): string {
  const parts: string[] = [];
  if (f.kind === "text" && f.pattern) parts.push(f.pattern.message);
  if (f.key === "dateOfBirth") parts.push("must be in the past");
  if (f.key === "to") parts.push("not before From");
  if (f.kind === "table" && f.minRows) parts.push(`at least ${f.minRows} row`);
  return parts.join("; ") || "type/length";
}

const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

function render(def: FormDefinition): string {
  const lines: string[] = [
    `## ${def.title} (template v${def.version})`,
    "",
    `Source: \`${def.sourceDocument}\` · Template: \`${def.templatePath}\` · Rendered pages: ${def.sourcePageCount}`,
    "",
    "| Key | Original label | Page | Section | Type | Repeatable | Requirement | Validation | Storage | PDF mapping | Tests |",
    "|---|---|---|---|---|---|---|---|---|---|---|",
  ];
  for (const s of def.sections)
    for (const f of s.fields) {
      const repeat = f.kind === "table" || f.kind === "list" ? "yes" : "no";
      const store = `revision.answers.${f.key}`;
      const pdf =
        f.kind === "derived"
          ? "computed at submission, printed"
          : `render.ts bind${def.code === "ASSISTANT_PROFESSOR" ? "Assistant" : "Associate"} → \`${f.key}\``;
      lines.push(
        `| \`${f.key}\` | ${esc(f.source.label)} | ${f.source.page} | ${esc(s.title)} | ${type(f)} | ${repeat} | ${f.requirement} | ${esc(validation(f))} | ${store} | ${pdf} | ${TEST_REF.split(";")[0]} |`,
      );
      if (f.kind === "table")
        for (const c of f.columns)
          lines.push(
            `| \`${f.key}[].${c.key}\` | ${esc(c.source.label)} | ${c.source.page} | ${esc(s.title)} | ${type(c)} | (row) | ${c.requirement} | ${esc(validation(c))} | ${store}[].${c.key} | table cell | ${TEST_REF.split(";")[0]} |`,
          );
    }
  lines.push(
    "",
    "### Preserved static content (never filled by the portal)",
    "",
    "| Id | Page | Text | Handling |",
    "|---|---|---|---|",
  );
  for (const p of def.preservedText) lines.push(`| ${p.id} | ${p.page} | ${esc(p.text)} | ${esc(p.note)} |`);
  return lines.join("\n");
}

const defs = listFormDefinitions();
const count = (d: FormDefinition) =>
  d.sections.reduce(
    (n, s) => n + s.fields.reduce((m, f) => m + 1 + (f.kind === "table" ? f.columns.length : 0), 0),
    0,
  );
const out = [
  "# Form field traceability inventory",
  "",
  "> Generated by `npm run forms:inventory` from `app/modules/forms/definitions/*`. Do not edit by hand.",
  "> Requirement `policy` = optional pending institutional confirmation.",
  "",
  ...defs.map((d) => `- ${d.title}: ${count(d)} inventoried fields/columns`),
  "",
  ...defs.map(render),
  "",
].join("\n");
writeFileSync("docs/requirements/form-field-inventory.md", out);
console.log(`wrote docs/requirements/form-field-inventory.md (${defs.map(count).join(" + ")} entries)`);
